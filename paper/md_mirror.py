"""Build paper/paper.md, the GitHub-readable Markdown mirror of paper/main.tex (MISSION §6.1).

pandoc reads IEEEtran sources but drops the title block and the abstract and keeps PDF figures,
which GitHub does not render. This script feeds pandoc a lightly rewritten copy of main.tex
(abstract as a normal section), then prepends the title and author and points figures at the PNG
versions generated next to each PDF. Requires pandoc on PATH. Usage: python3 md_mirror.py
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def flatten(tex: str) -> str:
    """Inline \\input files and undo two constructs pandoc drops silently: `table*` floats and
    `\\resizebox{..}{..}{content}` (every table inside them disappeared from the output)."""
    tex = re.sub(
        r"\\input\{([^}]+)\}",
        lambda m: flatten((HERE / (m.group(1).removesuffix(".tex") + ".tex")).read_text("utf-8")),
        tex,
    )
    tex = tex.replace("\\begin{table*}", "\\begin{table}").replace("\\end{table*}", "\\end{table}")
    while (m := re.search(r"\\resizebox\{[^}]*\}\{[^}]*\}\{", tex)) is not None:
        depth, end = 1, m.end()
        while depth:
            depth += {"{": 1, "}": -1}.get(tex[end], 0)
            end += 1
        tex = tex[: m.start()] + tex[m.end() : end - 1] + tex[end:]
    return tex


def title_author(main_tex: str) -> tuple[str, str]:
    title = re.search(r"\\title\{(.*?)\}\n", main_tex, re.S)
    author = re.search(r"\\IEEEauthorblockN\{(.*?)\}", main_tex)
    return (
        title.group(1).strip().replace("--", "\u2013") if title else "Paper",
        author.group(1).strip() if author else "",
    )


def main() -> int:
    main_tex = (HERE / "main.tex").read_text(encoding="utf-8")
    title, author = title_author(main_tex)
    abstract = (HERE / "sections" / "abstract.tex").read_text(encoding="utf-8")
    abstract = abstract.replace("\\begin{abstract}", "\\section*{Abstract}").replace(
        "\\end{abstract}", ""
    )
    abstract = re.sub(
        r"\\begin\{IEEEkeywords\}(.*?)\\end\{IEEEkeywords\}",
        r"\\paragraph*{Index terms} \1",
        abstract,
        flags=re.S,
    )
    body = flatten(
        main_tex.replace("\\input{sections/abstract}", abstract).replace("\\maketitle", "")
    )
    tmp = HERE / ".mirror.tex"
    tmp.write_text(body, encoding="utf-8")
    try:
        out = subprocess.run(
            [
                "pandoc",
                tmp.name,
                "--from",
                "latex",
                "--to",
                "gfm",
                "--citeproc",
                "--bibliography",
                "refs.bib",
                "--resource-path=.:sections",
            ],
            cwd=HERE,
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    finally:
        tmp.unlink(missing_ok=True)
    out = re.sub(r'<embed src="(figures/[^"]+)\.pdf" />', r'<img src="\1.png" width="100%" />', out)
    head = f"# {title}\n\n"
    if author:
        head += f"**{author}**\n\n"
    head += (
        "> Markdown mirror of `paper/main.tex`, generated by `paper/md_mirror.py` (do not edit). "
        "The PDF (`paper/main.pdf`) is authoritative; evidence labels: [T] verified-by-test, "
        "[D] from-official-docs, [3P] third-party-report.\n\n"
    )
    (HERE / "paper.md").write_text(head + out, encoding="utf-8")
    print(f"wrote {HERE / 'paper.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
