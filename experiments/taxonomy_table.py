"""Paper tables for the threat taxonomy (RQ1) and the canary-bench scenario/harness catalogue.

Writes, from committed sources only:
- paper/tables/taxonomy.tex|md from taxonomy/harness-threats.yaml (classes, STRIDE, OWASP, ATLAS,
  controls) and experiments/results/rq3_incidents.json (verified incident counts per class);
- paper/tables/bench_scenarios.tex|md from harnesswatch.bench.scenarios.SCENARIOS and
  harnesswatch.bench.adapters.ADAPTERS (scenario ids, vectors, adapter images and mode flags).
Usage: uv run python experiments/taxonomy_table.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from harnesswatch.bench.adapters import ADAPTERS  # noqa: E402
from harnesswatch.bench.scenarios import SCENARIOS, Canary  # noqa: E402

TABLES = ROOT / "paper" / "tables"


def esc(s: str) -> str:
    for a, b in (
        ("\\", r"\textbackslash{}"),
        ("&", r"\&"),
        ("%", r"\%"),
        ("_", r"\_"),
        ("#", r"\#"),
    ):
        s = s.replace(a, b)
    return s


def taxonomy() -> None:
    tax = yaml.safe_load((ROOT / "taxonomy" / "harness-threats.yaml").read_text(encoding="utf-8"))
    rq3_path = ROOT / "experiments" / "results" / "rq3_incidents.json"
    counts: dict[str, int] = {}
    if rq3_path.exists():
        counts = json.loads(rq3_path.read_text(encoding="utf-8"))["by_taxonomy_class"]
    rows, md = (
        [],
        [
            "| Class | Name | STRIDE | OWASP LLM | OWASP ASI | ATLAS | Controls | Incidents |",
            "|---|---|---|---|---|---|---|---|",
        ],
    )
    for c in tax["classes"]:

        def j(key: str, cls: dict[str, Any] = c) -> str:
            v = cls.get(key) or []
            return ", ".join(v) if isinstance(v, list) else str(v)

        atlas = c.get("mitre_atlas") or []
        atlas_s = ", ".join(a.replace("AML.", "") for a in atlas[:1]) + (
            ", \\dots" if len(atlas) > 1 else ""
        )
        n = counts.get(c["id"], 0)
        rows.append(
            f"{c['id']} & {esc(c['name'])} & {''.join(c.get('stride') or [])} & {j('owasp_llm_2025')} & "
            f"{j('owasp_agentic')} & {atlas_s or '--'} & {j('controls')} & {n} \\\\"
        )
        md.append(
            f"| {c['id']} | {c['name']} | {''.join(c.get('stride') or [])} | {j('owasp_llm_2025')} | "
            f"{j('owasp_agentic')} | {', '.join(atlas)} | {j('controls')} | {n} |"
        )
    tex = (
        "% generated by experiments/taxonomy_table.py; do not edit\n"
        "\\begin{table*}[t]\n\\centering\\scriptsize\\setlength{\\tabcolsep}{3pt}\n"
        "\\caption{Harness threat taxonomy (RQ1) with framework mappings, mitigating control dimensions "
        "(D01--D15, Section~\\ref{sec:controls}) and the number of verified 2025--2026 incidents whose "
        "primary class it is (RQ3). ATLAS ids are abbreviated (prefix \\texttt{AML.} dropped; first shown).}\n"
        "\\label{tab:taxonomy}\n"
        "\\begin{tabular}{lp{5.3cm}lp{1.9cm}p{2.3cm}p{1.7cm}p{2.9cm}r}\n\\toprule\n"
        "Class & Name & STRIDE & OWASP LLM & OWASP ASI & MITRE ATLAS & Controls & Inc. \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n\\end{table*}\n"
    )
    (TABLES / "taxonomy.tex").write_text(tex, encoding="utf-8")
    (TABLES / "taxonomy.md").write_text("\n".join(md) + "\n", encoding="utf-8")


def scenarios() -> None:
    probe = Canary("00000000", "hwsynth_x")
    rows, md = (
        [],
        ["| Scenario | Title | Taxonomy | Files changed vs. base repo |", "|---|---|---|---|"],
    )
    for s in SCENARIOS.values():
        files = sorted(s.files(probe, "<instruction file>"))
        f_tex = ", ".join(f"\\texttt{{{esc(f)}}}" for f in files) or "none"
        rows.append(f"\\texttt{{{esc(s.id)}}} & {esc(s.title)} & {esc(s.taxonomy)} & {f_tex} \\\\")
        md.append(f"| {s.id} | {s.title} | {s.taxonomy} | {', '.join(files) or 'none'} |")
    arows, amd = (
        [],
        ["| Harness | Tier | Image | Instruction file | Auto-mode flag |", "|---|---|---|---|---|"],
    )
    for a in ADAPTERS.values():
        base = a.command("TASK", "default", "MODEL")
        auto = [x for x in a.command("TASK", "auto", "MODEL") if x not in base]
        flag = " ".join(auto) or "--"
        arows.append(
            f"{esc(a.id)} & {a.tier} & \\texttt{{{esc(a.image.split(':')[-1])}}} & "
            f"\\texttt{{{esc(a.instruction_file)}}} & \\texttt{{{esc(flag)}}} \\\\"
        )
        amd.append(f"| {a.id} | {a.tier} | {a.image} | {a.instruction_file} | {flag} |")
    tex = (
        "% generated by experiments/taxonomy_table.py; do not edit\n"
        "\\begin{table*}[t]\n\\centering\\scriptsize\n"
        "\\caption{Canary-bench catalogue. Top: scenarios (all share the base repository and task; "
        "\\texttt{<instruction file>} is the harness-native file named below). Bottom: harness adapters, "
        "pinned image version, and the documented flag added in the \\emph{auto} mode.}\n"
        "\\label{tab:bench-catalogue}\n"
        "\\begin{tabular}{lp{5.2cm}lp{7.2cm}}\n\\toprule\n"
        "Scenario & Title & Taxonomy & Files changed vs.\\ base repository \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n\n\\medskip\n"
        "\\begin{tabular}{lllll}\n\\toprule\n"
        "Harness & Tier & Version & Instruction file & Auto-mode flag \\\\\n\\midrule\n"
        + "\n".join(arows)
        + "\n\\bottomrule\n\\end{tabular}\n\\end{table*}\n"
    )
    (TABLES / "bench_scenarios.tex").write_text(tex, encoding="utf-8")
    (TABLES / "bench_scenarios.md").write_text("\n".join([*md, "", *amd]) + "\n", encoding="utf-8")


def rubric() -> None:
    data = yaml.safe_load((ROOT / "matrix" / "rubric.yaml").read_text(encoding="utf-8"))
    rows, md = [], ["| Dim | Name | Question | Score 3 requires |", "|---|---|---|---|"]
    for d in data["dimensions"]:
        top = str(d.get("scores", {}).get(3, ""))
        rows.append(f"{d['id']} & {esc(d['name'])} & {esc(d['question'])} \\\\")
        md.append(f"| {d['id']} | {d['name']} | {d['question']} | {top} |")
    tex = (
        "% generated by experiments/taxonomy_table.py from matrix/rubric.yaml; do not edit\n"
        "\\begin{table}[!t]\n\\centering\\scriptsize\\setlength{\\tabcolsep}{3pt}\n"
        "\\caption{Control rubric summary (RQ2): the question each dimension answers. Each is scored "
        "0--3 against its own criteria (full text, including tier-C ladders, in \\texttt{matrix/rubric.md}).}\n"
        "\\label{tab:rubric}\n"
        "\\begin{tabular}{lp{1.9cm}p{5.6cm}}\n\\toprule\n"
        "Dim. & Name & Question \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n"
    )
    (TABLES / "rubric.tex").write_text(tex, encoding="utf-8")
    (TABLES / "rubric.md").write_text("\n".join(md) + "\n", encoding="utf-8")


def main() -> None:
    TABLES.mkdir(parents=True, exist_ok=True)
    taxonomy()
    scenarios()
    rubric()
    print("wrote paper/tables/{taxonomy,bench_scenarios,rubric}.{tex,md}")


if __name__ == "__main__":
    main()
