"""Rule-pack catalogue for the paper appendix (MISSION §6.1, appendix "full rule list").

Reads rules/HG-*.yaml and writes paper/tables/rules.tex (a table* float) and paper/tables/rules.md.
Nothing is hand-typed: id, severity, confidence, kind, taxonomy classes and title come from the YAML.
Usage: uv run python experiments/rules_table.py
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
RULES = ROOT / "rules"
OUT_TEX = ROOT / "paper" / "tables" / "rules.tex"
OUT_MD = ROOT / "paper" / "tables" / "rules.md"

KIND = {
    "vulnerability-pattern": "vuln.\\ pattern",
    "design-weakness": "design weakness",
    "policy": "policy choice",
}


def load() -> list[dict[str, Any]]:
    rules = [yaml.safe_load(p.read_text(encoding="utf-8")) for p in sorted(RULES.glob("HG-*.yaml"))]
    return sorted(rules, key=lambda r: str(r["id"]))


def tex_escape(s: str) -> str:
    out = []
    for ch in s:
        out.append(
            {
                "\\": r"\textbackslash{}",
                "&": r"\&",
                "%": r"\%",
                "_": r"\_",
                "#": r"\#",
                "$": r"\$",
                "{": r"\{",
                "}": r"\}",
                "~": r"\textasciitilde{}",
                "^": r"\textasciicircum{}",
                "|": r"\textbar{}",
            }.get(ch, ch)
        )
    text = "".join(out)
    # inline code spans in titles -> \texttt
    parts = text.split("`")
    return "".join(f"\\texttt{{{p}}}" if i % 2 else p for i, p in enumerate(parts))


def render_tex(rules: list[dict[str, Any]]) -> str:
    rows = []
    for r in rules:
        kind = KIND.get(str(r.get("kind", "")), tex_escape(str(r.get("kind", ""))))
        rows.append(
            f"\\texttt{{{tex_escape(str(r['id']))}}} & {r['severity']} & {r.get('confidence', '')} & "
            f"{kind} & {', '.join(r.get('taxonomy', []))} & {tex_escape(str(r['title']))} \\\\"
        )
    body = "\n".join(rows)
    return (
        "% generated by experiments/rules_table.py from rules/HG-*.yaml; do not edit\n"
        "\\begin{table*}[t]\n\\centering\\scriptsize\n"
        "\\caption{The \\texttt{harnesswatch} rule pack ("
        + str(len(rules))
        + " rules). Kind separates "
        "vulnerability patterns, design weaknesses (unsafe defaults or configurations) and policy "
        "choices; taxonomy classes refer to Table~\\ref{tab:taxonomy}.}\n"
        "\\label{tab:rules}\n"
        "\\begin{tabular}{llllp{2.3cm}p{7.9cm}}\n\\toprule\n"
        "Rule & Severity & Confidence & Kind & Taxonomy & Title \\\\\n\\midrule\n"
        f"{body}\n\\bottomrule\n\\end{{tabular}}\n\\end{{table*}}\n"
    )


def render_md(rules: list[dict[str, Any]]) -> str:
    lines = [
        "| Rule | Severity | Confidence | Kind | Taxonomy | Title |",
        "|---|---|---|---|---|---|",
    ]
    for r in rules:
        title = str(r["title"]).replace("|", "\\|")
        lines.append(
            f"| {r['id']} | {r['severity']} | {r.get('confidence', '')} | {r.get('kind', '')} | "
            f"{', '.join(r.get('taxonomy', []))} | {title} |"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    rules = load()
    OUT_TEX.parent.mkdir(parents=True, exist_ok=True)
    OUT_TEX.write_text(render_tex(rules), encoding="utf-8")
    OUT_MD.write_text(render_md(rules), encoding="utf-8")
    print(f"{len(rules)} rules -> {OUT_TEX.relative_to(ROOT)}, {OUT_MD.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
