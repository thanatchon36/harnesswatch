"""Generate the data-driven documentation pages. Deterministic, offline.

Writes under docs/reference/ and docs/taxonomy.md from the YAML sources of truth:
rules/HG-*.yaml, rules/harness_profiles/*.yaml, taxonomy/harness-threats.yaml.
Run via `make docs`.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
HEADER = "<!-- Generated by scripts/gen_docs.py from {src}. Do not edit. -->\n\n"


def _load(path: Path) -> Any:
    with path.open(encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def _cell(value: Any) -> str:
    """Escape a value for a Markdown table cell."""
    if value is None or value == "":
        return "-"
    return str(value).replace("|", "\\|").replace("\n", " ")


def _para(text: Any) -> str:
    return " ".join(str(text or "").split())


def _code_list(items: list[Any] | None) -> str:
    return ", ".join(f"`{i}`" for i in items) if items else "-"


def render_rules(rules: list[dict[str, Any]]) -> str:
    out = [HEADER.format(src="rules/HG-*.yaml"), "# Rule reference\n\n"]
    out.append(f"{len(rules)} rules. Severity is the default; some rules adjust it by context.\n\n")
    out.append("| ID | Area | Severity | Title |\n|---|---|---|---|\n")
    for r in rules:
        out.append(
            f"| [{r['id']}](#{r['id'].lower()}) | {_cell(r.get('area'))} | "
            f"{_cell(r.get('severity'))} | {_cell(r.get('title'))} |\n"
        )
    for r in rules:
        out.append(f"\n## {r['id']}\n\n**{_para(r.get('title'))}**\n\n")
        out.append(
            f"- Area: {_cell(r.get('area'))}\n- Severity: {_cell(r.get('severity'))}\n"
            f"- Confidence: {_cell(r.get('confidence'))}\n- Kind: {_cell(r.get('kind'))}\n"
            f"- Taxonomy: {_code_list(r.get('taxonomy'))}\n\n"
        )
        out.append(f"{_para(r.get('description'))}\n\n")
        out.append(f"**Remediation.** {_para(r.get('remediation'))}\n")
        refs = r.get("references") or []
        if refs:
            out.append("\n**References**\n\n" + "".join(f"- <{u}>\n" for u in refs))
    return "".join(out)


def render_profiles(profiles: list[dict[str, Any]]) -> str:
    out = [HEADER.format(src="rules/harness_profiles/*.yaml"), "# Harness profile reference\n\n"]
    out.append(
        f"{len(profiles)} harness profiles. Tier: A open source, B closed product, "
        "C runtime or SDK. Profiles are data read by `inventory` and the audits.\n\n"
    )
    out.append(
        "| ID | Name | Tier | Status | Version analysed | Config files |\n"
        "|---|---|---|---|---|---|\n"
    )
    for p in profiles:
        files = [str(c.get("path")) for c in p.get("config_files") or [] if isinstance(c, dict)]
        shown = "<br>".join(f"`{_cell(f)}`" for f in files[:6])
        if len(files) > 6:
            shown += f"<br>and {len(files) - 6} more"
        out.append(
            f"| `{p['id']}` | {_cell(p.get('name'))} | {_cell(p.get('tier'))} | "
            f"{_cell(p.get('status'))} | {_cell(p.get('version_analysed'))} | "
            f"{shown or '-'} |\n"
        )
    return "".join(out)


def render_taxonomy(tax: dict[str, Any]) -> str:
    out = [HEADER.format(src="taxonomy/harness-threats.yaml"), "# Threat taxonomy\n\n"]
    out.append(f"{_para(tax.get('title'))}. Status: {_para(tax.get('status'))}.\n\n")
    out.append("## Classification rule\n\n")
    for line in tax.get("classification_rule") or []:
        out.append(f"- {_para(line)}\n")
    classes = tax.get("classes") or []
    out.append("\n## Classes\n\n| ID | Name | Incidents | Rules |\n|---|---|---|---|\n")
    for c in classes:
        out.append(
            f"| [{c['id']}](#{c['id'].lower()}) | {_cell(c.get('name'))} | "
            f"{_cell(c.get('incident_count'))} | {_code_list(c.get('rules'))} |\n"
        )
    for c in classes:
        out.append(
            f"\n### {c['id']}\n\n**{_para(c.get('name'))}**\n\n{_para(c.get('definition'))}\n\n"
        )
        out.append(f"- Harness surfaces: {_code_list(c.get('harness_surfaces'))}\n")
        for key, label in (
            ("mitre_atlas", "MITRE ATLAS"),
            ("owasp_llm_2025", "OWASP LLM 2025"),
            ("owasp_agentic", "OWASP Agentic"),
            ("owasp_mcp", "OWASP MCP"),
            ("stride", "STRIDE"),
        ):
            out.append(f"- {label}: {_code_list(c.get(key))}\n")
        if c.get("distinguishes"):
            out.append(f"\n*What is different in a harness.* {_para(c['distinguishes'])}\n")
    gaps = tax.get("gaps") or []
    if gaps:
        out.append("\n## Known gaps\n\n" + "".join(f"- {_para(g)}\n" for g in gaps))
    return "".join(out)


def render_scenarios(scenarios: list[tuple[str, str, str]]) -> str:
    out = [
        HEADER.format(src="src/harnesswatch/bench/scenarios.py"),
        "| Scenario | Description | Taxonomy |\n|---|---|---|\n",
    ]
    for sid, title, tax in scenarios:
        out.append(f"| `{sid}` | {_cell(title)} | {_cell(tax)} |\n")
    return "".join(out)


def load_scenarios() -> list[tuple[str, str, str]]:
    from harnesswatch.bench.scenarios import SCENARIOS

    return [(s.id, s.title, s.taxonomy) for s in SCENARIOS.values()]


def generate(
    root: Path = ROOT, scenarios: list[tuple[str, str, str]] | None = None
) -> dict[Path, str]:
    """Return {output path: content} without writing anything."""
    rules = [_load(p) for p in sorted((root / "rules").glob("HG-*.yaml"))]
    rules.sort(key=lambda r: r["id"])
    profiles = [_load(p) for p in sorted((root / "rules" / "harness_profiles").glob("*.yaml"))]
    profiles.sort(key=lambda p: p["id"])
    tax = _load(root / "taxonomy" / "harness-threats.yaml")
    docs = root / "docs"
    return {
        docs / "reference" / "rules.md": render_rules(rules),
        docs / "reference" / "profiles.md": render_profiles(profiles),
        docs / "taxonomy.md": render_taxonomy(tax),
        docs / "reference" / "bench-scenarios.md": render_scenarios(
            scenarios if scenarios is not None else load_scenarios()
        ),
    }


def main() -> int:
    for path, content in generate().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
