"""Render brief/executive-brief.md (and .pdf) from the template; numbers come from paper/numbers.tex.

Every {{macro}} in the template is replaced with the value generated by experiments/paper_numbers.py,
so the brief, like the paper, carries no hand-typed result numbers. Unknown macros fail the build.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MACRO = re.compile(r"\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}")


def macros() -> dict[str, str]:
    out = {}
    for line in (ROOT / "paper" / "numbers.tex").read_text(encoding="utf-8").splitlines():
        match = MACRO.fullmatch(line.strip())
        if match:
            out[match.group(1)] = match.group(2).replace("\\%", "%")
    return out


def render(template: str, values: dict[str, str]) -> str:
    def sub(match: re.Match[str]) -> str:
        name = match.group(1)
        if name not in values:
            raise KeyError(f"unknown macro in brief template: {name}")
        return values[name]

    return re.sub(r"\{\{([A-Za-z]+)\}\}", sub, template)


def main() -> None:
    brief = ROOT / "brief"
    text = render((brief / "executive-brief.md.tmpl").read_text(encoding="utf-8"), macros())
    (brief / "executive-brief.md").write_text(text, encoding="utf-8")
    tectonic = ROOT / ".tools" / "tectonic"
    if shutil.which("pandoc") and tectonic.exists() and "--no-pdf" not in sys.argv:
        subprocess.run(
            [
                "pandoc",
                "executive-brief.md",
                "-o",
                "executive-brief.pdf",
                f"--pdf-engine={tectonic}",
                "-V",
                "geometry:margin=1.6cm",
                "-V",
                "fontsize=10pt",
            ],
            cwd=brief,
            check=True,
        )
    print(f"rendered {brief / 'executive-brief.md'}")


if __name__ == "__main__":
    main()
